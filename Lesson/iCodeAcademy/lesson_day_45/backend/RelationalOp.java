public class RelationalOp {
    public static void main(String[] args) {
        System.out.println("Relational Operation");
        int a = 10;
        int b = 20;
        System.out.println(a == b);
        System.out.println(a != b);
        System.out.println(a > b);
        System.out.println(a < b);
        System.out.println(a >= b);
        System.out.println(a <= b);
        
        boolean result = a > b;
        System.out.println(result);

        char c = 'A';
        System.out.println(a > b);
        System.out.println(c > 'B');

        
    }
}
