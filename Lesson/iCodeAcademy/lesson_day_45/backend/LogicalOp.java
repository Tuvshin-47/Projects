public class LogicalOp {
    public static void main(String[] args) {
        System.out.println("Logical Operators");
        boolean a = true;
        boolean b = false;
        System.out.println(a && b); // false
        System.out.println(a || b); // true
        System.out.println(!a); // false
        // let a:int = 6;
    }    
}
